import PDFDocument from "pdfkit"

export const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size:   "A4",
      margin: 50,
      info: {
        Author:  "VERTEX AI",
        Title:   data.title,
        Creator: "VERTEX AI AI Platform",
      },
    })

    const chunks = []
    doc.on("data",  (chunk) => chunks.push(chunk))
    doc.on("end",   ()      => resolve(Buffer.concat(chunks)))
    doc.on("error", (err)   => reject(err))

    // ── Title ──────────────────────────────────────────────────────────
    doc
      .fontSize(28)
      .fillColor("#111827")
      .text(data.title, { align: "center" })

    if (data.subtitle) {
      doc.moveDown(0.5)
      doc
        .fontSize(12)
        .fillColor("#6B7280")
        .text(data.subtitle, { align: "center" })
    }

    doc.moveDown(1)

    // ── Separator ─────────────────────────────────────────────────────
    doc
      .moveTo(50, doc.y)
      .lineTo(545, doc.y)
      .strokeColor("#E5E7EB")
      .lineWidth(1)
      .stroke()

    doc.moveDown(1.5)

    // ── Sections ──────────────────────────────────────────────────────
    data?.sections?.forEach((s) => {
      doc
        .fontSize(16)
        .fillColor("#1D4ED8")
        .text(s.heading)

      doc.moveDown(0.4)

      s?.points?.forEach((p) => {
        doc
          .fontSize(11)
          .fillColor("#374151")
          .text("• " + p, { lineGap: 4 })
      })

      doc.moveDown(1)
    })

    // ── Footer ────────────────────────────────────────────────────────
    doc
      .moveDown(1)
      .fontSize(9)
      .fillColor("#9CA3AF")
      .text("Generated by VERTEX AI AI Platform", { align: "center" })

    doc.end()
  })
}
